# ── 개인정보 감지: AI에 보내기 전에 막습니다 ─────────────────────
_PII_PATTERNS = {
    "전화번호": re.compile(r"01[016789][-\s.]?\d{3,4}[-\s.]?\d{4}"),
    "이메일": re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+"),
    "주민등록번호": re.compile(r"\d{6}[-\s]?[1-4]\d{6}"),
}


# ── 말투 다듬기: 가끔 섞이는 보고서체·명령형 문장 끝을 해요체로 ─────────────
_POLISH = [  # (문장 끝 표현, 바꿀 말) — 뒤의 마침표·느낌표는 그대로 둡니다
    ("됩니다", "돼요"), ("합니다", "해요"), ("있습니다", "있어요"), ("없습니다", "없어요"),
    ("없다요", "없어요"), ("하라", "하세요"),
]


def polish(text: str) -> str:
    """AI 답변 끝맺음에 섞인 '~됩니다/~합니다/~하라'를 해요체로 바꿉니다(내용은 그대로)."""
    for old, new in _POLISH:
        text = re.sub(re.escape(old) + r"(?=[.!]|\s*$)", new, text, flags=re.M)
    return text


def find_personal_info(text: str) -> list[str]:
    return [name for name, pattern in _PII_PATTERNS.items() if pattern.search(text)]
